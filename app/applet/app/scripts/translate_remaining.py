def build(translations, target_path):
    with open('app/src/main/res/values-en/strings.xml', 'r', encoding='utf-8') as f:
        en_content = f.read()

    pattern = re.compile(r'<string name="([^"]+)">([^<]*)</string>')
    missing = []

    def repl(match):
        key = match.group(1)
        val = match.group(2)
        if key in translations:
            tval = translations[key]
            if "'" in tval and not "\\'" in tval:
                tval = tval.replace("'", "\\'")
            return f'<string name="{key}">{tval}</string>'
        else:
            missing.append(key)
            return f'<string name="{key}">{val}</string>'

    new_content = pattern.sub(repl, en_content)
    with open(target_path, 'w', encoding='utf-8') as f:
        f.write(new_content)
    print(f"File {target_path} written. Missing keys: {len(missing)}")
    if missing:
        print("Missing:", missing)

build(RU_ALL, 'app/src/main/res/values-ru/strings.xml')
build(DE_ALL, 'app/src/main/res/values-de/strings.xml')
