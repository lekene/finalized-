def xml_escape_val(tval):
    tval = re.sub(r'&(?!(amp|lt|gt|quot|apos);)', '&amp;', tval)
    tval = re.sub(r"(?<!\\)'", r"\'", tval)
    tval = re.sub(r'(?<!\\)"', r'\"', tval)
    return tval

def generate_locale_file(translations, target_path):
    with open('app/src/main/res/values-en/strings.xml', 'r', encoding='utf-8') as f:
        en_content = f.read()

    pattern = re.compile(r'<string name="([^"]+)">([^<]*)</string>')
    missing = []

    def repl(match):
        key = match.group(1)
        val = match.group(2)
        if key in translations:
            tval = translations[key]
            tval = xml_escape_val(tval)
            return f'<string name="{key}">{tval}</string>'
        else:
            missing.append(key)
            val = xml_escape_val(val)
            return f'<string name="{key}">{val}</string>'

    new_content = pattern.sub(repl, en_content)
    with open(target_path, 'w', encoding='utf-8') as f:
        f.write(new_content)
        
    print(f"File {target_path} successfully generated. Missing keys count: {len(missing)}")
    if missing:
        print("Missing keys:", missing)

generate_locale_file(RU_TOTAL, 'app/src/main/res/values-ru/strings.xml')
